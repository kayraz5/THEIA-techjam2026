"""Render results tables from each arm's eval outputs.

Writes:
  results/<arm>/RESULTS.md   one per results folder — that arm's full report
  results/RESULTS.md         combined view: headline index + every arm's report

Reads results/<arm>/eval/{summary.json,auc_grid.csv} plus any data-ablation CSVs
(auc_grid_ablation_*.csv from scripts/data_ablation.py, or the legacy
auc_grid_sid_only_ablation.csv).

  python scripts/make_results.py
"""
from __future__ import annotations
import glob, json, os
import pandas as pd

GRID_COLS = ["transform", "level", "auc_coco_real", "delta_coco", "err_coco_real",
             "auc_alt_real", "shortcut_gap", "bal_acc@0.5"]
PREAMBLE = ("Auto-generated by `python scripts/make_results.py`. Headline metric: **ROC AUC**.\n"
            "The designated validation set is class-imbalanced (real:fake about 1:1.77, majority-class "
            "accuracy about 0.65), so accuracy is never reported without balanced accuracy and that baseline "
            "beside it. Every row is reported against two independent real sets — COCO (the organisers' "
            "reals) and a held-out ImageNet set — because a large gap between them would indicate the model "
            "learned \"looks like COCO\" rather than \"is real\".\n")


def _table(df: pd.DataFrame, cols: list[str]) -> str:
    cols = [c for c in cols if c in df.columns]
    return df[cols].fillna("").to_markdown(index=False, floatfmt=".4f")


def arm_section(arm: str, img_prefix: str) -> str:
    """Render one arm. img_prefix is the path prefix from the output file to the arm dir."""
    s = json.load(open(os.path.join(arm, "eval", "summary.json")))
    out = [f"## {s['config']}", "",
           f"`{s['backbone']}` — {s['backbone_params_B']:.3f} B parameters "
           f"(hard limit 2 B, asserted at every model load)", ""]

    out += ["| Measurement | AUC | error (1 − AUC) |", "|---|---|---|",
            f"| clean, **full** designated val set (n={s['n_full_set']}) | **{s['clean_auc_full_set']:.4f}** | {1 - s['clean_auc_full_set']:.4f} |"]
    if "clean_auc_full_set_dedup" in s:
        out.append(f"| clean, full set **deduplicated** (n={s['n_full_set_dedup']}: {s['n_real_dedup']} real / {s['n_fake_dedup']} unique fake) "
                   f"| {s['clean_auc_full_set_dedup']:.4f} | {1 - s['clean_auc_full_set_dedup']:.4f} |")
    out += [f"| clean, eval subset, fakes vs COCO reals | {s['clean_auc']:.4f} | {1 - s['clean_auc']:.4f} |",
            f"| clean, eval subset, fakes vs **ImageNet (alt) reals** | {s['clean_auc_alt_real']:.4f} | {1 - s['clean_auc_alt_real']:.4f} |",
            f"| worst single transform: `{s['worst_transform']}` | {s['worst_auc']:.4f} (alt real {s['worst_auc_alt_real']:.4f}) | {1 - s['worst_auc']:.4f} |",
            "",
            f"**Shortcut gap (COCO-real AUC − alt-real AUC, clean): {s['shortcut_gap_clean']:+.4f}** — a large positive "
            f"gap would mean the model is exploiting the COCO capture pipeline rather than detecting generation.",
            "",
            f"Max degradation delta: **{s['max_delta']:.4f}** · mean degraded AUC: {s['mean_degraded_auc']:.4f}", ""]
    if "full_set_acc@0.5" in s:
        out += [f"Accuracy at threshold 0.5 on the full set: {s['full_set_acc@0.5']:.4f}, balanced accuracy "
                f"{s['full_set_bal_acc@0.5']:.4f} — against a majority-class baseline of "
                f"{s['majority_class_baseline_acc']:.4f} (class ratio {s['class_ratio_real:fake']}).", ""]

    grid = os.path.join(arm, "eval", "auc_grid.csv")
    if os.path.exists(grid):
        out += ["### Per-transform grid (eval subset)", "", _table(pd.read_csv(grid), GRID_COLS), "",
                f"![AUC grid]({img_prefix}eval/auc_grid.png)", ""]

    for abl in sorted(glob.glob(os.path.join(arm, "eval", "auc_grid_ablation_*.csv"))
                      + glob.glob(os.path.join(arm, "eval", "auc_grid_sid_only_ablation.csv"))):
        name = os.path.basename(abl).replace("auc_grid_ablation_", "").replace("auc_grid_", "").replace(".csv", "")
        sj = os.path.join(arm, "eval", f"summary_ablation_{name}.json")
        out += [f"### Data ablation: `{name}`", "",
                "Same frozen features and the same head-training procedure — only the training sources differ.", ""]
        if os.path.exists(sj):
            a = json.load(open(sj))
            out += [f"Trained on {a['n_train_features']} features from sources matching `{a['keep']}`. "
                    f"Clean AUC (full set) **{a['clean_auc_full_set']:.4f}**, worst cell `{a['worst_transform']}` "
                    f"{a['worst_auc']:.4f}, max delta {a['max_delta']:.4f}.", ""]
        out += [_table(pd.read_csv(abl), GRID_COLS), ""]

    thr = os.path.join(arm, "eval", "thresholds.csv")
    if "thresholds" in s or os.path.exists(thr):
        t = pd.DataFrame(s["thresholds"]) if "thresholds" in s else pd.read_csv(thr)
        out += ["### Operating points (clean images)", "",
                "`FPR_real` is the fraction of genuine photos wrongly flagged; on a platform serving billions of "
                "images this is the cost that matters, which is why it is reported per threshold rather than only "
                "as a single accuracy figure.", "",
                t.fillna("").to_markdown(index=False, floatfmt=".4f"), ""]

    out += ["### Figures", "",
            f"- ROC curve: `{img_prefix}eval/roc.png`",
            f"- FPR vs threshold: `{img_prefix}eval/fpr_vs_threshold.png`",
            f"- Error analysis contact sheets: `{img_prefix}eval/errors_fp.png` (false positives), "
            f"`{img_prefix}eval/errors_fn.png` (false negatives), `{img_prefix}eval/errors_top.csv`",
            f"- Checkpoint / training history: `{img_prefix}head_best.pt`, `{img_prefix}train_history.json`", ""]
    return "\n".join(out)


def main():
    arms = sorted(os.path.dirname(os.path.dirname(p)) for p in glob.glob("results/*/eval/summary.json"))
    if not arms:
        print("no results/*/eval/summary.json found — run src.evaluate first"); return

    for arm in arms:
        body = [f"# Results — {os.path.basename(arm)}", "", PREAMBLE, arm_section(arm, "")]
        open(os.path.join(arm, "RESULTS.md"), "w").write("\n".join(body) + "\n")
        print(f"wrote {arm}/RESULTS.md")

    idx = [{"arm": (s := json.load(open(os.path.join(a, "eval", "summary.json"))))["config"],
            "clean_auc_full_set": s["clean_auc_full_set"], "worst_transform": s["worst_transform"],
            "worst_auc": s["worst_auc"], "max_delta": s["max_delta"],
            "shortcut_gap": s["shortcut_gap_clean"], "params_B": round(s["backbone_params_B"], 3)}
           for a in arms]
    combined = ["# Results", "", PREAMBLE, "## All arms", "",
                pd.DataFrame(idx).to_markdown(index=False, floatfmt=".4f"), "",
                "Per-arm reports: " + " · ".join(f"[{os.path.basename(a)}]({os.path.basename(a)}/RESULTS.md)" for a in arms), ""]
    for arm in arms:
        combined += [arm_section(arm, os.path.basename(arm) + "/"), "---", ""]
    if os.path.exists("results/comparison.csv"):
        combined += ["## Baseline comparison (`src/compare.py`)", "",
                     pd.read_csv("results/comparison.csv").to_markdown(index=False, floatfmt=".4f"), ""]
    open("results/RESULTS.md", "w").write("\n".join(combined) + "\n")
    print("wrote results/RESULTS.md (combined)")


if __name__ == "__main__":
    main()
